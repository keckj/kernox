def fig_reduction(flat=None):
    """The M x N matrix that is never stored, reduced tile by tile."""
    f = Fig(660, 390, "A reduction over j: the M by N matrix is computed tile by tile and never stored", flat)
    c, M, N = 28, 8, 12
    gx, gy = 150, 100            # matrix
    lx, ty, ox = 92, 52, 560     # x_i column, y_j row, output column
    tr, tc = (2, 5), (4, 8)      # the highlighted tile: rows [2, 5), columns [4, 8)
    # inputs
    f.text(gx + N * c / 2, ty - 14, "y_{j}  (Vj, N rows)", 13, "ink2")
    for j in range(N):
        on = tc[0] <= j < tc[1]
        f.rect(gx + j * c + 2, ty, c - 4, c - 4, "c1l" if on else "panel", "c1" if on else "line", rx=3)
    f.text(lx + c / 2 - 2, gy - 14, "x_{i}  (Vi, M rows)", 13, "ink2")
    for i in range(M):
        on = tr[0] <= i < tr[1]
        f.rect(lx, gy + i * c + 2, c - 4, c - 4, "c1l" if on else "panel", "c1" if on else "line", rx=3)
    # the virtual matrix
    for i in range(M):
        for j in range(N):
            f.rect(gx + j * c + 2, gy + i * c + 2, c - 4, c - 4, None, "grid", 1, rx=2, dash="3 2")
    f.rect(gx + tc[0] * c, gy + tr[0] * c, (tc[1] - tc[0]) * c, (tr[1] - tr[0]) * c, "c1l", "c1", 2, rx=4)
    for i in range(*tr):
        for j in range(*tc):
            f.text(gx + j * c + c / 2, gy + i * c + c / 2 + 4, "f", 12, "c1", italic=True)
    f.text(gx + N * c / 2, gy + M * c + 22, "f(x_{i}, y_{j}) for every pair: never stored", 13, "ink2")
    f.text(gx + (tc[0] + tc[1]) / 2 * c, gy + tr[0] * c - 7, "one tile, in registers", 12, "c1")
    # reduction arrow and output
    ym = gy + (tr[0] + tr[1]) / 2 * c
    f.arrow(gx + tc[1] * c + 6, ym, ox - 10, ym, "c2", 2)
    f.text((gx + tc[1] * c + ox) / 2, ym - 10, "reduce over j", 12, "c2")
    f.text(ox + c / 2 - 2, gy - 14, "result", 13, "ink2")
    for i in range(M):
        on = tr[0] <= i < tr[1]
        f.rect(ox, gy + i * c + 2, c - 4, c - 4, "c2l" if on else "panel", "c2" if on else "line", rx=3)
    f.text(ox + c / 2 - 2, gy + M * c + 22, "M rows", 13, "ink2")
    f.text(330, 375, "Memory: the inputs and the result only, linear in M + N.", 13, "ink")
    return f


