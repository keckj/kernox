"""Figures of the documentation: SVG files in docs/images/, drawn from code.

    python tools/make_figures.py            # writes docs/images/*.svg and docs/stylesheets/figures.css
    python tools/make_figures.py --preview DIR   # also flat light and dark copies, for a quick look

Each figure is a plain SVG. Its colours are CSS variables on the class
``kxfig``: a standalone file (README on GitHub) follows the light or dark
setting of the system, and the documentation site, which inlines the SVG
(tools/mkdocs_hooks.py), follows the theme toggle through figures.css. The
measurements drawn in the charts are the tables of the documentation.
"""
