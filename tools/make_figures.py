def fig_split(flat=None):
    """split="output" and split="reduced" with four processes."""
    f = Fig(720, 330, "The two ways kd.reduce splits a reduction across four processes", flat)
    s, P = 160, 4
    for panel, (x0, name) in enumerate(((30, 'split="output"'), (390, 'split="reduced"'))):
        f.text(x0 + 150, 26, name, 15, "ink", weight=True, mono=True)
        f.text(x0 + s / 2, 54, "j (reduced axis)", 12, "ink2")
        f.text(x0 - 10, 70 + s / 2, "i (output rows)", 12, "ink2", rotate=-90)
        for p in range(P):
            if panel == 0:
                x, y, w, h = x0, 66 + p * s / P, s, s / P
            else:
                x, y, w, h = x0 + p * s / P, 66, s / P, s
            f.rect(x + 1, y + 1, w - 2, h - 2, PROC[p] + "l", PROC[p], 1.5, rx=3)
            f.text(x + w / 2, y + h / 2 + 5, f"P{p}", 13, "ink", weight=True)
        ax = x0 + s + 12
        if panel == 0:
            # each process: its rows of the output; all_gather
            for p in range(P):
                f.rect(ax + 10, 66 + p * s / P + 1, 16, s / P - 2, PROC[p], None, rx=2)
            f.arrow(ax + 34, 66 + s / 2, ax + 84, 66 + s / 2, "ink2", 1.5)
            f.text(ax + 59, 66 + s / 2 - 10, "all_gather", 12, "ink2", mono=True)
            for p in range(P):
                f.rect(ax + 92, 66 + p * s / P + 1, 16, s / P - 2, PROC[p], None, rx=2)
            notes = ["Each process computes its rows of the", "output exactly; they are then gathered.",
                     "Exchange: the size of the output."]
        else:
            # each process: a partial result for every row; merge
            for p in range(P):
                f.rect(ax + 6 + p * 9, 67, 7, s - 2, PROC[p], None, rx=2)
            f.arrow(ax + 48, 66 + s / 2, ax + 84, 66 + s / 2, "ink2", 1.5)
            f.text(ax + 66, 66 + s / 2 - 10, "merge", 12, "ink2")
            f.rect(ax + 92, 67, 16, s - 2, "ink2", None, rx=2)
            notes = ["Each process reduces over its part of j;", "the partial results are merged (sum, min,",
                     "log-sum-exp, ...). For short outputs."]
        f.text(ax + 100, 66 + s + 20, "result", 12, "ink2")
        for k, t in enumerate(notes):
            f.text(x0 - 14, 270 + 19 * k, t, 13, "ink", "start")
    return f


