def scaling_chart(data, title, xlabel, flat=None, unit="devices"):
    """Speed-up against the number of devices, one panel per platform, both axes in log scale
    (the ideal speed-up is then the diagonal)."""
    panels = list(data.items())
    pw, ph, left, top, gap = 280, 220, 58, 62, 190
    f = Fig(left + len(panels) * (pw + gap) - 20, top + ph + 70, title, flat)
    P = [1, 2, 4, 8]
    for k, (name, series) in enumerate(panels):
        x0 = left + k * (pw + gap)
        def X(p):
            return x0 + math.log2(p) / 3 * pw
        def Y(s):
            return top + ph - math.log2(s) / math.log2(10) * ph
        f.text(x0, top - 30, name, 13, "ink", "start", weight=True)
        for s in P:
            f.line(x0, Y(s), x0 + pw, Y(s), "grid")
            f.text(x0 - 8, Y(s) + 4, f"{s}", 11, "ink2", "end")
        for p in P:
            f.text(X(p), top + ph + 18, f"{p}", 11, "ink2")
        f.text(x0 + pw / 2, top + ph + 40, xlabel, 12, "ink2")
        if k == 0:
            f.text(x0 - 36, top + ph / 2, "speed-up", 12, "ink2", rotate=-90)
        f.line(X(1), Y(1), X(8), Y(8), "line", 1.5, "5 4")
        f.text(X(2.8) - 8, Y(2.8) - 4, "ideal", 11, "ink2", "end")
        ends = []
        for i, (label, t, *at8) in enumerate(series):  # at8: the speed-up of the table, from unrounded times
            sp = [t[0] / v for v in t]
            col = PROC[i]
            f.path("M" + " L".join(f"{X(p):.1f},{Y(v):.1f}" for p, v in zip(P, sp)), None, col, 2)
            for p, v in zip(P, sp):
                f.circle(X(p), Y(v), 4.5, col, "bg", 2)
            ends.append([Y(sp[-1]), label, f"× {at8[0] if at8 else round(sp[-1], 1)}", col])
        # direct labels at the right end, pushed apart
        ends.sort()
        for i in range(1, len(ends)):
            ends[i][0] = max(ends[i][0], ends[i - 1][0] + 30)
        for y, label, val, col in ends:
            f.text(X(8) + 12, y + 0, label, 11, "ink", "start")
            f.text(X(8) + 12, y + 14, val, 11, col, "start", weight=True)
    return f


